#include <iostream>
using namespace std;

int main()
{
  /*
    1100
  & 0101
  ---------
    0100 = 4
  */
  cout << "12 & 5 = " << (12 & 5) << endl;

  /*
    1100
  | 0101
  ---------
    1101 = 13
  */
  cout << "12 | 5 = " << (12 | 5) << endl;

  /*
    1100
  ^ 0101
  ---------
    1001 = 9
  */
  cout << "12 ^ 5 = " << (12 ^ 5) << endl;

  /*
    10 << 1
    = 1010 << 1
    = 10100
    = 20

    OR

    10 << 1
    = 10 * power(2, 1)
    = 10 * 2
    = 20
  */

  cout << "10 << 1 = " << (10 << 1) << endl;

  /*
    10 >> 2
    = 1010 >> 2
    = 0010
    = 2

    OR

    10 >> 2
    = 10 / power(2, 2)
    = 10 / 4
    = 2
  */

  cout << "10 >> 2 = " << (10 >> 2) << endl;
  return 0;
}